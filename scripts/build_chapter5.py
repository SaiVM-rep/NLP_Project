"""Chapter 5 for the report: docs/chapter5_draft.md + generated tables -> docs/chapter5.md.

    make chapter5      (after `make report`)

The draft holds the prose and markers; every number in a table comes from
results/report/tables.md (written by eval/report.py from the run logs), so nothing in
chapter 5 is retyped (SC5). Markers:

    <!-- table: E1 -->                              section "E1: ..." of tables.md
    <!-- figure: e3_levels.png | caption -->        results/report/e3_levels.png

Tables and figures are numbered 5.1, 5.2, ... in order of appearance. A marker naming a
table that does not exist is an error, so a stale draft cannot silently drop a table.
Leading "> " note lines of the draft (instructions for the team) are left out.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = re.compile(r"<!--\s*(table|figure):\s*(.+?)\s*-->")
HEADER = (
    "<!-- generated by scripts/build_chapter5.py from docs/chapter5_draft.md + "
    "results/report/tables.md; edit those, not this file -->\n\n"
)


def split_tables(md: str) -> dict[str, tuple[str, str]]:
    """'## E1: Route A ...' -> {'E1': (full heading, table body)}; key = text before ':' or ' ('."""
    out: dict[str, tuple[str, str]] = {}
    for block in re.split(r"^## ", md, flags=re.M)[1:]:
        heading, _, body = block.partition("\n")
        key = re.split(r":| \(", heading, maxsplit=1)[0].strip()
        out[key] = (heading.strip(), body.strip() + "\n")
    return out


def _drop_draft_notes(draft: str) -> str:
    lines = draft.splitlines()
    first = next((i for i, ln in enumerate(lines) if ln.startswith("> ")), None)
    if first is None:
        return draft
    end = first
    while end < len(lines) and lines[end].startswith(">"):
        end += 1
    return "\n".join(lines[:first] + lines[end:]).replace("\n\n\n", "\n\n") + "\n"


def assemble(draft: str, tables: dict[str, tuple[str, str]], *, fig_dir: str) -> str:
    n = {"table": 0, "figure": 0}

    def sub(m: re.Match[str]) -> str:
        kind, arg = m.group(1), m.group(2)
        n[kind] += 1
        if kind == "table":
            heading, body = tables[arg]  # KeyError names the missing table
            return f"**Table 5.{n[kind]} — {heading}**\n\n{body.rstrip()}"
        name, _, caption = (s.strip() for s in arg.partition("|"))
        return f"![Figure 5.{n[kind]} — {caption or name}]({fig_dir}/{name})"

    return HEADER + MARKER.sub(sub, _drop_draft_notes(draft))


def main() -> int:
    draft = (ROOT / "docs" / "chapter5_draft.md").read_text(encoding="utf-8")
    tables = split_tables((ROOT / "results" / "report" / "tables.md").read_text(encoding="utf-8"))
    out = ROOT / "docs" / "chapter5.md"
    out.write_text(assemble(draft, tables, fig_dir="../results/report"), encoding="utf-8")
    used = len(MARKER.findall(_drop_draft_notes(draft)))
    print(f"wrote {out.relative_to(ROOT)} ({used} tables/figures from results/report/)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
