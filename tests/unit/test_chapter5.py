"""Chapter 5 assembly: draft text + generated tables, nothing retyped (SC5)."""

import pytest
from scripts.build_chapter5 import assemble, split_tables

TABLES = """# Chapter 5 tables (generated by `make report`; do not edit)

## Verifier thresholds (AggreFact dev, 4349 rows)

| a | b |
| --- | --- |
| 1 | 2 |

## E1: Route A vs forced Route B (run `x`)

| arm | f |
| --- | --- |
| A | 0.7 |
"""


def test_split_tables_keys_by_heading_name() -> None:
    t = split_tables(TABLES)
    assert set(t) == {"Verifier thresholds", "E1"}
    heading, body = t["E1"]
    assert heading == "E1: Route A vs forced Route B (run `x`)"
    assert body.startswith("| arm | f |") and body.rstrip().endswith("| A | 0.7 |")


def test_markers_become_numbered_tables_and_figures() -> None:
    draft = (
        "# Ch 5\n\nIntro.\n\n<!-- table: Verifier thresholds -->\n\nText.\n\n"
        "<!-- table: E1 -->\n\n<!-- figure: e3_levels.png | Faithfulness per level -->\n"
    )
    out = assemble(draft, split_tables(TABLES), fig_dir="../results/report")
    assert "**Table 5.1 — Verifier thresholds (AggreFact dev, 4349 rows)**" in out
    assert "**Table 5.2 — E1: Route A vs forced Route B (run `x`)**" in out
    assert "| A | 0.7 |" in out
    assert "![Figure 5.1 — Faithfulness per level](../results/report/e3_levels.png)" in out
    assert "<!--" not in out.split("\n", 2)[2]  # no marker left (header comment aside)
    assert out.startswith("<!-- generated by scripts/build_chapter5.py")


def test_unknown_table_marker_fails_loudly() -> None:
    with pytest.raises(KeyError, match="E9"):
        assemble("<!-- table: E9 -->", split_tables(TABLES), fig_dir=".")


def test_draft_editing_notes_are_dropped() -> None:
    draft = "# Ch 5\n\n> Draft text for the team report.\n> more note\n\nBody.\n"
    out = assemble(draft, split_tables(TABLES), fig_dir=".")
    assert "Draft text" not in out and "Body." in out
